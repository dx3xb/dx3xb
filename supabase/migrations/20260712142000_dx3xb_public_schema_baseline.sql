create or replace function public.dx3xb_bump_play(app_slug text) returns void
language sql security definer set search_path = public
as $$ update public.dx3xb_microapps set plays = plays + 1 where slug = app_slug and status in ('unlisted','pending','public') $$;

create or replace function public.dx3xb_gb_ratelimit() returns trigger
language plpgsql set search_path = public, pg_temp
as $$
begin
  if new.ip is not null and new.ip <> '' then
    if (select count(*) from public.dx3xb_guestbook where ip = new.ip and created_at > now() - interval '1 minute') >= 5 then
      raise exception 'rate_limited';
    end if;
    if exists (
      select 1 from public.dx3xb_guestbook
       where ip = new.ip and lower(message) = lower(new.message) and created_at > now() - interval '24 hours'
    ) then raise exception 'duplicate_message'; end if;
  end if;
  if length(new.message) > 280 or array_length(regexp_split_to_array(lower(new.message), 'https?://|www\.'), 1) > 3 then
    raise exception 'spam';
  end if;
  return new;
end;
$$;

create or replace function public.dx3xb_ma_ratelimit() returns trigger
language plpgsql set search_path = public, pg_temp
as $$
begin
  if (select count(*) from public.dx3xb_microapps where owner_id = new.owner_id and created_at > now() - interval '1 hour') >= 12 then
    raise exception 'rate_limited';
  end if;
  return new;
end;
$$;

drop trigger if exists dx3xb_gb_rl on public.dx3xb_guestbook;
create trigger dx3xb_gb_rl before insert on public.dx3xb_guestbook for each row execute function public.dx3xb_gb_ratelimit();
