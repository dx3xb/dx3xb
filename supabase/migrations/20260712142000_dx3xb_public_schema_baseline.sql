create table if not exists public.dx3xb_guestbook (
  id bigint generated always as identity primary key,
  name text not null,
  message text not null,
  created_at timestamptz not null default now(),
  parent_id bigint references public.dx3xb_guestbook(id) on delete cascade,
  ip text,
  country text,
  city text,
  region text,
  hidden boolean not null default false
);

create table if not exists public.dx3xb_microapps (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  slug text not null unique,
  title text not null default '',
  template text not null default 'quiz',
  config jsonb not null default '{}'::jsonb,
  status text not null default 'draft' check (status in ('draft','unlisted','pending','public','hidden')),
  plays integer not null default 0 check (plays >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.dx3xb_microapp_events (
  id bigint generated by default as identity primary key,
  microapp_id uuid not null references public.dx3xb_microapps(id) on delete cascade,
  event text not null check (event in ('view','start','complete','share')),
  created_at timestamptz not null default now(),
  user_id uuid,
  session_id text
);

create table if not exists public.dx3xb_microapp_reports (
  id bigint generated always as identity primary key,
  microapp_id uuid references public.dx3xb_microapps(id) on delete cascade,
  reason text,
  created_at timestamptz default now()
);

create table if not exists public.dx3xb_play_results (
  id uuid primary key default gen_random_uuid(),
  microapp_id uuid not null references public.dx3xb_microapps(id) on delete cascade,
  label text not null,
  score integer check (score between 0 and 100),
  created_at timestamptz not null default now()
);

create table if not exists public.dx3xb_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  handle text,
  created_at timestamptz default now()
);

create table if not exists public.dx3xb_runs (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  game text not null,
  score integer not null default 0,
  pct integer,
  title text,
  stats jsonb,
  lang text,
  created_at timestamptz default now()
);

create table if not exists public.dx3xb_subscribers (
  id bigint generated always as identity primary key,
  email text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.dx3xb_toys (
  id bigint generated always as identity primary key,
  slug text not null unique,
  title_zh text not null,
  title_en text not null,
  desc_zh text default '',
  desc_en text default '',
  icon text default '🧸',
  type text not null default 'external' check (type in ('external','internal')),
  url text default '',
  status text not null default 'coming_soon' check (status in ('live','coming_soon','maintenance','hidden')),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

